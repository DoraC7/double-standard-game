    for (let col = 0; col < size; col++) lines.push(Array.from({length: size}, (_, row) => row * size + col));
    lines.push(Array.from({length: size}, (_, i) => i * size + i), Array.from({length: size}, (_, i) => i * size + size - i - 1));
    return lines.filter(line => line.every(index => selected.has(index)));
